#!/usr/bin/env python
"""Write the data behind the report's figures from committed results.

    python scripts/figure_data.py           # rewrite reports/figures/data/
    python scripts/figure_data.py --check   # exit 1 when a file is out of date

The pgfplots figures in reports/figures/ read only these files, so every
plotted number comes from a committed result:

- metric_labels.csv: the metric names, in plot order;
- deltas_v2.csv, deltas_v3.csv: the gate's paired difference (candidate minus
  baseline) per metric with its confidence interval and verdict, from
  results/v2_improved_vs_v1_baseline.json and
  results/v3_fluent_regression_vs_v1_baseline.json;
- runner.csv: wall time, failed cases and rate-limit responses of each runner
  configuration, from results/runner_benchmark.json;
- params.tex: the gate's tolerance (RegressionThresholds().default) and the
  confidence level of the intervals (1 - alpha from the comparisons).

tests/test_figure_data.py runs --check, so a changed result fails the build
until the data is regenerated.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from aire.regression.compare import RegressionThresholds

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
OUT = ROOT / "reports" / "figures" / "data"

# The metrics of the report's per-version table, top to bottom, with the
# label the table uses.
METRICS = (
    ("retrieval_recall_at_1", r"retrieval\_recall@1"),
    ("retrieval_recall_at_3", r"retrieval\_recall@3"),
    ("retrieval_mrr_at_3", r"retrieval\_MRR@3"),
    ("keyword_recall", r"keyword\_recall"),
    ("gold_citation_recall", r"gold\_citation\_recall"),
    ("citation_precision", r"citation\_precision"),
    ("groundedness", "groundedness"),
    ("abstention_correct", r"abstention\_correct"),
    ("success_rate", r"success\_rate"),
)
COMPARISONS = {
    "v2": "v2_improved_vs_v1_baseline.json",
    "v3": "v3_fluent_regression_vs_v1_baseline.json",
}
RUNS = (
    ("sequential", "1 worker"),
    ("concurrent", "8 workers"),
    ("over_eager", "8 workers (budget too high)"),
    ("warm_cache", "8 workers (warm cache)"),
)


def _load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _fmt(value: float) -> str:
    return f"{value:.6g}"


def _y(position: int, count: int) -> int:
    """Plot position: the first entry is drawn at the top."""
    return count - 1 - position


def label_table() -> str:
    """The y tick labels of the delta plot, in ascending y."""
    lines = ["y,label"]
    for position, (_, label) in reversed(list(enumerate(METRICS))):
        lines.append(f"{_y(position, len(METRICS))},{label}")
    return "\n".join(lines) + "\n"


def delta_table(comparison: dict[str, Any]) -> str:
    """One row per metric that has a paired interval, in ascending y."""
    rows = {row["metric"]: row for row in comparison["metrics"]}
    # minus and plus are the distances from the delta to the interval ends.
    lines = ["y,delta,minus,plus,verdict"]
    for position, (metric, _) in reversed(list(enumerate(METRICS))):
        row = rows.get(metric, {})
        if row.get("ci_low") is None or row.get("ci_high") is None:
            continue  # no paired interval: the metric is missing from a run
        delta, low, high = row["paired_delta"], row["ci_low"], row["ci_high"]
        lines.append(
            f"{_y(position, len(METRICS))},{_fmt(delta)},{_fmt(delta - low)},"
            f"{_fmt(high - delta)},{row['verdict']}"
        )
    return "\n".join(lines) + "\n"


def runner_table(benchmark: dict[str, Any]) -> str:
    runs = {run["label"]: run for run in benchmark["runs"]}
    lines = ["y,label,wall_s,failed,rate_limited,requests"]
    for position, (key, label) in reversed(list(enumerate(RUNS))):
        run = runs[key]
        lines.append(
            f"{_y(position, len(RUNS))},{label},{run['wall_time_s']},{run['n_failed']},"
            f"{run['server']['rate_limited']},{run['server']['requests']}"
        )
    return "\n".join(lines) + "\n"


def params_tex(comparisons: dict[str, dict[str, Any]]) -> str:
    # The gate's intervals are paired bootstrap intervals at 1 - alpha.
    levels = {1.0 - c["statistics"]["alpha"] for c in comparisons.values()}
    if len(levels) != 1:
        raise ValueError(f"the comparisons use different confidence levels: {sorted(levels)}")
    level = levels.pop()
    return (
        "% Generated by scripts/figure_data.py from committed results; do not edit.\n"
        f"\\newcommand{{\\aireTolerance}}{{{RegressionThresholds().default:g}}}\n"
        f"\\newcommand{{\\aireConfidence}}{{{level * 100:g}}}\n"
    )


def render() -> dict[str, str]:
    """Every data file, keyed by its name in reports/figures/data/."""
    comparisons = {key: _load(RESULTS / name) for key, name in COMPARISONS.items()}
    files = {f"deltas_{key}.csv": delta_table(c) for key, c in comparisons.items()}
    files["metric_labels.csv"] = label_table()
    files["runner.csv"] = runner_table(_load(RESULTS / "runner_benchmark.json"))
    files["params.tex"] = params_tex(comparisons)
    return files


def sync(check: bool) -> list[str]:
    stale: list[str] = []
    for name, text in render().items():
        path = OUT / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current is None or current.replace("\r\n", "\n") != text:
            stale.append(name)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write the figure data from committed results.")
    parser.add_argument("--check", action="store_true", help="change nothing; exit 1 if stale")
    args = parser.parse_args(argv)
    try:
        stale = sync(check=args.check)
    except (OSError, KeyError, ValueError) as exc:
        print(f"error: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 2
    for name in stale:
        verb = "stale" if args.check else "updated"
        print(f"{verb}: reports/figures/data/{name}", file=sys.stderr if args.check else sys.stdout)
    return 1 if (args.check and stale) else 0


if __name__ == "__main__":
    raise SystemExit(main())
